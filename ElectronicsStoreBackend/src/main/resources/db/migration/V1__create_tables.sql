

CREATE TABLE users (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       email VARCHAR(255) NOT NULL UNIQUE,
                       password VARCHAR(255) NOT NULL,
                       first_name VARCHAR(255) NOT NULL,
                       last_name VARCHAR(255) NOT NULL,
                       phone VARCHAR(255),
                       role VARCHAR(50) NOT NULL,
                       enabled BOOLEAN NOT NULL DEFAULT TRUE,
                       email_verified BOOLEAN NOT NULL DEFAULT FALSE,
                       last_login_at TIMESTAMP,
                       created_at TIMESTAMP,
                       updated_at TIMESTAMP
);


CREATE TABLE addresses (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           title VARCHAR(255),
                           country VARCHAR(255) NOT NULL,
                           city VARCHAR(255) NOT NULL,
                           street VARCHAR(255) NOT NULL,
                           building VARCHAR(255),
                           apartment VARCHAR(255),
                           postal_code VARCHAR(255),
                           recipient_name VARCHAR(255),
                           recipient_phone VARCHAR(255),
                           is_default BOOLEAN NOT NULL DEFAULT FALSE,
                           latitude DOUBLE PRECISION,
                           longitude DOUBLE PRECISION,
                           user_id BIGINT NOT NULL REFERENCES users(id)
);


CREATE TABLE brands (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        name VARCHAR(255) NOT NULL UNIQUE,
                        slug VARCHAR(255) NOT NULL UNIQUE,
                        description VARCHAR(1000),
                        logo_url VARCHAR(255),
                        website_url VARCHAR(255),
                        country VARCHAR(255),
                        is_active BOOLEAN NOT NULL DEFAULT TRUE
);


CREATE TABLE categories (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            name VARCHAR(255) NOT NULL,
                            slug VARCHAR(255) NOT NULL UNIQUE,
                            description VARCHAR(1000),
                            image_url VARCHAR(255),
                            sort_order INTEGER DEFAULT 0,
                            is_active BOOLEAN NOT NULL DEFAULT TRUE,
                            parent_category_id BIGINT REFERENCES categories(id)
);


CREATE TABLE products (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          name VARCHAR(255) NOT NULL,
                          slug VARCHAR(255) NOT NULL UNIQUE,
                          description TEXT,
                          short_description VARCHAR(255),
                          sku VARCHAR(255) NOT NULL UNIQUE,
                          base_price NUMERIC(12, 2) NOT NULL,
                          discount_price NUMERIC(12, 2),
                          discount_start_date TIMESTAMP,
                          discount_end_date TIMESTAMP,
                          stock_quantity INTEGER NOT NULL DEFAULT 0,
                          reserved_quantity INTEGER NOT NULL DEFAULT 0,
                          low_stock_threshold INTEGER DEFAULT 5,
                          weight NUMERIC(12, 2),
                          dimensions VARCHAR(255),
                          is_active BOOLEAN NOT NULL DEFAULT TRUE,
                          is_featured BOOLEAN NOT NULL DEFAULT FALSE,
                          is_new_arrival BOOLEAN NOT NULL DEFAULT FALSE,
                          average_rating NUMERIC(3, 2),
                          review_count INTEGER DEFAULT 0,
                          view_count BIGINT DEFAULT 0,
                          sales_count BIGINT DEFAULT 0,
                          meta_title VARCHAR(255),
                          meta_description VARCHAR(1000),
                          created_at TIMESTAMP,
                          updated_at TIMESTAMP,
                          brand_id BIGINT REFERENCES brands(id),
                          category_id BIGINT NOT NULL REFERENCES categories(id)
);


CREATE TABLE product_images (
                                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                image_url VARCHAR(255) NOT NULL,
                                thumbnail_url VARCHAR(255),
                                alt_text VARCHAR(255),
                                is_primary BOOLEAN NOT NULL DEFAULT FALSE,
                                sort_order INTEGER DEFAULT 0,
                                product_id BIGINT NOT NULL REFERENCES products(id)
);


CREATE TABLE product_variants (
                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  sku VARCHAR(255) NOT NULL UNIQUE,
                                  name VARCHAR(255),
                                  attributes JSONB,
                                  price NUMERIC(12, 2),
                                  stock_quantity INTEGER NOT NULL DEFAULT 0,
                                  reserved_quantity INTEGER NOT NULL DEFAULT 0,
                                  image_url VARCHAR(255),
                                  is_active BOOLEAN NOT NULL DEFAULT TRUE,
                                  product_id BIGINT NOT NULL REFERENCES products(id)
);


CREATE TABLE product_specifications (
                                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                        name VARCHAR(255) NOT NULL,
                                        value TEXT,
                                        group_name VARCHAR(255),
                                        sort_order INTEGER DEFAULT 0,
                                        product_id BIGINT NOT NULL REFERENCES products(id)
);


CREATE TABLE reviews (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         rating INTEGER NOT NULL,
                         title VARCHAR(255),
                         comment TEXT,
                         pros TEXT,
                         cons TEXT,
                         images JSONB,
                         is_verified_purchase BOOLEAN NOT NULL DEFAULT FALSE,
                         helpful_count INTEGER NOT NULL DEFAULT 0,
                         not_helpful_count INTEGER NOT NULL DEFAULT 0,
                         admin_reply TEXT,
                         admin_reply_at TIMESTAMP,
                         status VARCHAR(50) NOT NULL,
                         created_at TIMESTAMP,
                         updated_at TIMESTAMP,
                         product_id BIGINT NOT NULL REFERENCES products(id),
                         user_id BIGINT NOT NULL REFERENCES users(id)
);


CREATE TABLE carts (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       session_id VARCHAR(255),
                       applied_promo_code VARCHAR(255),
                       created_at TIMESTAMP,
                       updated_at TIMESTAMP,
                       user_id BIGINT REFERENCES users(id)
);


CREATE TABLE cart_items (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            quantity INTEGER NOT NULL,
                            price_at_add NUMERIC(12, 2) NOT NULL,
                            cart_id BIGINT NOT NULL REFERENCES carts(id),
                            product_id BIGINT NOT NULL REFERENCES products(id),
                            variant_id BIGINT REFERENCES product_variants(id)
);


CREATE TABLE wishlists (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           price_at_add NUMERIC(12, 2),
                           notify_on_price_drop BOOLEAN NOT NULL DEFAULT FALSE,
                           notify_on_back_in_stock BOOLEAN NOT NULL DEFAULT FALSE,
                           added_at TIMESTAMP,
                           user_id BIGINT NOT NULL REFERENCES users(id),
                           product_id BIGINT NOT NULL REFERENCES products(id)
);


CREATE TABLE orders (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        order_number VARCHAR(255) NOT NULL UNIQUE,
                        status VARCHAR(50) NOT NULL,
                        country VARCHAR(255),
                        city VARCHAR(255),
                        street VARCHAR(255),
                        building VARCHAR(255),
                        apartment VARCHAR(255),
                        postal_code VARCHAR(255),
                        recipient_name VARCHAR(255),
                        recipient_phone VARCHAR(255),
                        latitude DOUBLE PRECISION,
                        longitude DOUBLE PRECISION,
                        delivery_method VARCHAR(50),
                        delivery_tracking_number VARCHAR(255),
                        estimated_delivery_date DATE,
                        actual_delivery_date DATE,
                        subtotal NUMERIC(12, 2) NOT NULL,
                        shipping_cost NUMERIC(12, 2) NOT NULL DEFAULT 0,
                        discount NUMERIC(12, 2) NOT NULL DEFAULT 0,
                        bonus_points_used INTEGER NOT NULL DEFAULT 0,
                        bonus_points_earned INTEGER NOT NULL DEFAULT 0,
                        total_amount NUMERIC(12, 2) NOT NULL,
                        promo_code VARCHAR(255),
                        customer_note TEXT,
                        admin_note TEXT,
                        created_at TIMESTAMP,
                        updated_at TIMESTAMP,
                        paid_at TIMESTAMP,
                        shipped_at TIMESTAMP,
                        delivered_at TIMESTAMP,
                        user_id BIGINT NOT NULL REFERENCES users(id)
);


CREATE TABLE order_items (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             quantity INTEGER NOT NULL,
                             price_at_purchase NUMERIC(12, 2) NOT NULL,
                             product_snapshot JSONB,
                             order_id BIGINT NOT NULL REFERENCES orders(id),
                             product_id BIGINT NOT NULL REFERENCES products(id),
                             variant_id BIGINT REFERENCES product_variants(id)
);


CREATE TABLE payments (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          transaction_id VARCHAR(255),
                          payment_method VARCHAR(50) NOT NULL,
                          status VARCHAR(50) NOT NULL,
                          amount NUMERIC(12, 2) NOT NULL,
                          currency VARCHAR(3) NOT NULL DEFAULT 'KZT',
                          bonus_points_used INTEGER NOT NULL DEFAULT 0,
                          card_last_four_digits VARCHAR(4),
                          paid_at TIMESTAMP,
                          error_message VARCHAR(255),
                          error_code VARCHAR(255),
                          refunded_amount NUMERIC(12, 2) DEFAULT 0,
                          metadata JSONB,
                          order_id BIGINT NOT NULL UNIQUE REFERENCES orders(id)
);


CREATE TABLE delivery_options (
                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  name VARCHAR(255) NOT NULL,
                                  code VARCHAR(255) NOT NULL UNIQUE,
                                  description TEXT,
                                  base_price NUMERIC(12, 2) NOT NULL,
                                  free_threshold NUMERIC(12, 2),
                                  estimated_days_min INTEGER,
                                  estimated_days_max INTEGER,
                                  is_active BOOLEAN NOT NULL DEFAULT TRUE
);


CREATE TABLE promo_codes (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             code VARCHAR(255) NOT NULL UNIQUE,
                             description TEXT,
                             discount_type VARCHAR(50) NOT NULL,
                             discount_value NUMERIC(12, 2) NOT NULL,
                             min_order_amount NUMERIC(12, 2),
                             max_discount_amount NUMERIC(12, 2),
                             max_usage_count INTEGER,
                             current_usage_count INTEGER NOT NULL DEFAULT 0,
                             max_usage_per_user INTEGER,
                             valid_from TIMESTAMP,
                             valid_to TIMESTAMP,
                             is_active BOOLEAN NOT NULL DEFAULT TRUE,
                             created_by VARCHAR(255)
);


CREATE TABLE promo_code_categories (
                                       promo_code_id BIGINT NOT NULL REFERENCES promo_codes(id),
                                       category_id BIGINT NOT NULL REFERENCES categories(id),
                                       PRIMARY KEY (promo_code_id, category_id)
);


CREATE TABLE promo_code_products (
                                     promo_code_id BIGINT NOT NULL REFERENCES promo_codes(id),
                                     product_id BIGINT NOT NULL REFERENCES products(id),
                                     PRIMARY KEY (promo_code_id, product_id)
);


CREATE TABLE promo_code_usages (
                                   id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                   discount_applied NUMERIC(12, 2) NOT NULL,
                                   used_at TIMESTAMP NOT NULL,
                                   promo_code_id BIGINT NOT NULL REFERENCES promo_codes(id),
                                   user_id BIGINT NOT NULL REFERENCES users(id),
                                   order_id BIGINT NOT NULL REFERENCES orders(id)
);


CREATE TABLE refresh_tokens (
                                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                token VARCHAR(255) NOT NULL UNIQUE,
                                expiry_date TIMESTAMP NOT NULL,
                                revoked BOOLEAN NOT NULL DEFAULT FALSE,
                                created_at TIMESTAMP NOT NULL,
                                user_id BIGINT NOT NULL REFERENCES users(id)
);


CREATE INDEX idx_addresses_user ON addresses(user_id);

CREATE INDEX idx_product_images_product ON product_images(product_id);
CREATE INDEX idx_product_variants_product ON product_variants(product_id);
CREATE INDEX idx_product_specifications_product ON product_specifications(product_id);

CREATE INDEX idx_reviews_product ON reviews(product_id);
CREATE INDEX idx_reviews_user ON reviews(user_id);

CREATE INDEX idx_cart_items_cart ON cart_items(cart_id);
CREATE INDEX idx_cart_items_product ON cart_items(product_id);

CREATE INDEX idx_wishlists_user ON wishlists(user_id);
CREATE INDEX idx_wishlists_product ON wishlists(product_id);

CREATE INDEX idx_orders_user ON orders(user_id);

CREATE INDEX idx_order_items_order ON order_items(order_id);
CREATE INDEX idx_order_items_product ON order_items(product_id);

CREATE INDEX idx_promo_code_usages_code ON promo_code_usages(promo_code_id);
CREATE INDEX idx_promo_code_usages_user ON promo_code_usages(user_id);

CREATE INDEX idx_refresh_tokens_user ON refresh_tokens(user_id);

CREATE INDEX idx_product_category ON products(category_id);
CREATE INDEX idx_product_brand ON products(brand_id);
CREATE INDEX idx_product_active ON products(is_active);